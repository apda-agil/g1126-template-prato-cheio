
import pg from 'pg';

const { Pool } = pg;
const EM_TESTE = process.env.VITEST === 'true' || process.env.NODE_ENV === 'test';

// Um banco exclusivo de testes é obrigatório.
const url = EM_TESTE
  ? process.env.DATABASE_TEST_URL
  : process.env.DATABASE_URL;

let pool;


function identificarBanco(connectionString) {
  const parsed = new URL(connectionString);

  if (!['postgres:', 'postgresql:'].includes(parsed.protocol)) {
    throw new Error('URL do PostgreSQL inválida');
  }

  const banco = decodeURIComponent(parsed.pathname.slice(1));

  return {
    host: parsed.hostname.toLowerCase(),
    porta: parsed.port || '5432',
    banco
  };
}


function configuracao() {
  if (!url) {
    throw new Error(EM_TESTE
      ? 'Defina DATABASE_TEST_URL para um banco PostgreSQL exclusivo de testes'
      : 'Defina DATABASE_URL para conectar ao PostgreSQL');
  }

  const parsed = new URL(url);

  if (!['postgres:', 'postgresql:'].includes(parsed.protocol)) {
    throw new Error('URL do PostgreSQL inválida');
  }

  if (EM_TESTE) {
    const nome = decodeURIComponent(parsed.pathname.slice(1));
    const producao = process.env.DATABASE_URL;

    if (!/(_test|_teste|_tests|_testes)$/.test(nome)) {
      throw new Error(
        'Banco de testes bloqueado: o nome deve terminar em _test ou _teste'
      );
    }

    
if (producao) {
  const teste = identificarBanco(url);
  const aplicacao = identificarBanco(producao);

  if (
    teste.host === aplicacao.host &&
    teste.porta === aplicacao.porta &&
    teste.banco === aplicacao.banco
  ) {
    throw new Error(
      'Banco de testes bloqueado: não pode ser o banco da aplicação'
    );
  }
}

  }

  return { connectionString: url };
}

// Cria a conexão com o PostgreSQL
export function conexao() {
  if (!pool) {
    pool = new Pool(configuracao());
  }
  return pool;
}

// Executa consultas SQL
export async function query(sql, valores = []) {
  return conexao().query(sql, valores);
}

// Cria a tabela de doações
export async function migrar() {
  await query(`
    CREATE TABLE IF NOT EXISTS doacoes (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tipo TEXT NOT NULL,
      quantidade TEXT NOT NULL,
      validade TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'disponivel',
      ong TEXT,
      criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      doador TEXT,
      coletada_em TIMESTAMPTZ
    )
  `);

  await atualizarSchemaLegado();
}

// Adiciona colunas ausentes em tabelas existentes
export async function atualizarSchemaLegado() {
  await query('ALTER TABLE doacoes ADD COLUMN IF NOT EXISTS doador TEXT');
  await query('ALTER TABLE doacoes ADD COLUMN IF NOT EXISTS coletada_em TIMESTAMPTZ');
}

// Limpa somente o banco exclusivo de testes
export async function limparBanco() {
  if (!EM_TESTE) {
    throw new Error('limparBanco bloqueado: permitido apenas durante testes');
  }

  configuracao();

  await query('TRUNCATE TABLE doacoes RESTART IDENTITY');
}

// Encerra a conexão
export async function encerrar() {
  if (pool) {
    await pool.end();
    pool = undefined;
  }
}
